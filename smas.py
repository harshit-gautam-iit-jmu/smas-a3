# Q11 - Image Transformation Toolbox

import numpy as np
from PIL import Image
import matplotlib.pyplot as plt

# Upload image
image_path = input("Enter image file path (.jpg/.png): ")

img = Image.open(image_path).convert("RGB")
img_array = np.array(img)

def show_image(image, title):
    plt.figure(figsize=(6, 6))
    plt.imshow(image)
    plt.title(title)
    plt.axis("off")
    plt.show()

def rotate_image(image, angle):
    return image.rotate(angle, expand=True)

def resize_image(image, scale):
    w, h = image.size
    return image.resize((int(w * scale), int(h * scale)))

def flip_image(image, direction):
    if direction == "horizontal":
        return image.transpose(Image.Transpose.FLIP_LEFT_RIGHT)
    elif direction == "vertical":
        return image.transpose(Image.Transpose.FLIP_TOP_BOTTOM)

def shear_image(image, shear):
    w, h = image.size
    matrix = (1, shear, 0, 0, 1, 0)
    return image.transform(
        (w, h),
        Image.Transform.AFFINE,
        matrix
    )

def custom_matrix(image, A):
    img_array = np.array(image)
    h, w, _ = img_array.shape

    cx = w / 2
    cy = h / 2

    y, x = np.mgrid[0:h, 0:w]

    x_centered = x - cx
    y_centered = cy - y

    points = np.vstack((
        x_centered.ravel(),
        y_centered.ravel()
    ))

    new_points = A @ points

    new_x = np.round(new_points[0] + cx).astype(int)
    new_y = np.round(cy - new_points[1]).astype(int)

    result = np.zeros_like(img_array)

    valid = (
        (new_x >= 0) & (new_x < w) &
        (new_y >= 0) & (new_y < h)
    )

    old_x = x.ravel()[valid]
    old_y = y.ravel()[valid]

    result[
        new_y[valid],
        new_x[valid]
    ] = img_array[old_y, old_x]

    return Image.fromarray(result)


