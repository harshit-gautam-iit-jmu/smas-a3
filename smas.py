cy = height / 2

# Create pixel coordinates relative to image centre
y, x = np.mgrid[0:height, 0:width]

x_centered = x - cx
y_centered = cy - y

points = np.vstack((x_centered.ravel(), y_centered.ravel()))

# Transformation matrices
A1 = np.array([
    [2, 0],
    [0, 0.5]
])

